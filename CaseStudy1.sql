----------------------------------------------Task 23---------------------------------------------
/*
Give the total weekly sales value with the date and product ID details. Use
 roll-up to pull the data in hierarchical order.
*/
SELECT YEAR(Date) AS Year, DATEPART(WEEK, Date) AS Week, ProductId, SUM(Sales) AS TotalWeeklySales
FROM fact
GROUP BY YEAR(Date), DATEPART(WEEK, Date), ProductId WITH ROLLUP;

